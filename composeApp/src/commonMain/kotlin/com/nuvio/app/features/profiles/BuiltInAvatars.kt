/** CINEBOX avatars: served as static files, so the picker works without the Supabase catalog. */
internal val BuiltInAvatars: List<AvatarCatalogItem> = BuiltInAvatarSpecs.mapIndexed { index, spec ->
    AvatarCatalogItem(
        id = "cinebox_${spec.key}",
        displayName = spec.name,
        storagePath = "$BuiltInAvatarBaseUrl${spec.key}.png",
        category = spec.category,
        sortOrder = index,
        bgColor = spec.bgColor,
    )
}
